;;; Rendering options that used to live in config; now read from the schema
;;; itself (with these as fallback defaults) since they're presentation
;;; details of a particular schema, not deployment config.
(def default-graph-options
  {:categories {:default {:color "#a9cce3"}}
   :render {:edge-labels? :minimal
            ;; :width / :height: max graph size in pixels (scales down only)
            :orientation :vertical
            ;; Edge labels as xlabels, placed after layout; regular labels become layout nodes and spread the graph sideways
            :xlabels? true
            ;; :graph-attrs, :node-attrs, :edge-attrs are merged over hyperphor.multitool.graph/default-attrs
            :graph-attrs {:nodesep 0.15 :ranksep 0.6}
            ;; Inheritance edges alone determine layout (parents above children); for ontologies
            :taxonomy? false
            ;; Group each category's kinds into a labeled Graphviz cluster (needs 2+ categories in use)
            :clusters? false
            ;; Node labels longer than this split over two lines at a word boundary (nil: never); narrows the graph
            :label-wrap 14
            ;; Run Graphviz unflatten with this -l level to stagger wide ranks of leaves (nil: don't)
            :unflatten 4
            ;; Lay out inheritance alone, components packed into a block, then draw relations straight over it.
            ;; For big, shallow taxonomies, which dot otherwise makes very wide; ignores :clusters?
            :pack? false
            }})

(defn- with-graph-defaults
  [schema]
  (u/merge* default-graph-options schema))

(defn- kind-url
  [kind]
  (str (name kind) ".html"))

(defn- static-ctx
  "Render context for static pages, see hyperphor.alzabo.render."
  [schema]
  {:schema schema :href kind-url :index-href "index.html"})

(defn output-file
  [output-path file]
  (str (fs/file output-path file)))

(def alzabo-link "https://github.com/hyperphor/alzabo")

(defn- page-header
  [{:keys [title version]}]
  [:div.header
   [:h1 [:a {:href "index.html"} title " " version]]
   [:div#app]
   [:span "Generated by " [:a {:href alzabo-link} "Alzabo"]]])

(defn html-out
  "Write a full page with header (title, search widget) and scripts around `body` (hiccup)."
  [output-path file title schema body]
  (prn :writing (output-file output-path file))
  (spit (output-file output-path file)
        (str
         (h/html {:mode :html}
           (raw-string "<!DOCTYPE html>\n")
           [:html
            [:head
             [:title title]
             [:meta {:charset "UTF-8"}]
             [:meta {:name "viewport" :content "width=device-width, initial-scale=1"}]
             [:link {:href "https://fonts.googleapis.com/css?family=Lato:400,700"
                     :rel "stylesheet"}]
             [:link {:href "https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/css/bootstrap.min.css"
                     :rel "stylesheet"
                     :integrity "sha384-QWTKZyjpPEjISv5WaRU9OFeRpok6YctnYmDr5pNlyT2bRjXh0JMhjY6hW+ALEwIH"
                     :crossorigin "anonymous"}]
             [:link {:rel "stylesheet" :href "alzabo.css"}]]
            [:body
             (page-header schema)
             body
             [:div.footer "Generated by " [:a {:href alzabo-link} "Alzabo"]]
             ;; See hyperphor.alzabo.search.core/run
             [:script {:src "schema.js"}]
             [:script {:src "client.js"}]
             [:script (raw-string "hyperphor.alzabo.search.core.run();")]]]))))

(defn- schema-js
  "JS source that sets window.alzaboSchema to `schema` as an EDN string."
  [schema]
  (str "window.alzaboSchema = "
       (s/replace (json/generate-string (binding [*print-length* nil *print-level* nil] (pr-str schema)))
                  "</" "<\\/")
       ";\n"))

(defn enum-samples
  [enum]
  (str (s/join ", " (map second (take 3 (:values enum))))
       (when (> (count (:values enum)) 3) "...")))

(defn- category-legend
  "Color key for the graph: one swatch per category in `used`."
  [categories used]
  [:div.legend
   (for [cat used
         :let [{:keys [color label doc]} (get categories cat)]]
     [:span.legend-item {:title (or doc "")}
      [:span.legend-swatch {:style {:background color}}]
      (or label (inflect/titleize (name cat)))])])

(defn- index->html
  "Index body: graph pane (inline `svg`) beside a side pane holding the detail mount point and kind/enum lists."
  [{:keys [kinds enums explanation] :as schema} svg]
  (let [ctx (static-ctx schema)
        categories (:categories (with-graph-defaults schema))
        groups (group-by #(get % :category :default) (vals (u/self-label :id kinds)))
        ;; Categories that actually have kinds, in declared order
        used (filter groups (keys categories))]
    [:div.az-index
     [:div.az-graph-pane
      (when (> (count used) 1)
        (category-legend categories used))
      [:div.az-graph (raw-string svg)]]
     [:div.az-side
      [:div#az-detail]
      [:div.az-lists
       (when explanation
         (into [:div.explanation] explanation))
       [:h2 "Entities"]                 ;aka Kinds, I suppose this should be configurable
       (for [category-name used]
         (let [kinds (category-name groups)
               category (category-name categories)]
           [:div
            (when (> (count used) 1)
              [:h3.category-header {:style {:background (:color category)}}
               (or (:label category)
                   (inflect/titleize category-name))])
            [:table.table.table-sm
             [:tbody
              (for [kind (sort-by :id kinds)]
                [:tr {:data-kind (name (:id kind))}
                 [:th (render/kind-link ctx (:id kind))]
                 [:td (render/linkify (:doc kind))]])]]]))
       [:h2 "Enums"]
       [:table.table.table-sm
        [:tbody
         (for [enum (sort (keys enums))]
           [:tr {:data-kind (name enum)}
            [:th (render/kind-link ctx enum)]
            [:td (render/linkify (:doc (get enums enum)))]
            [:td (enum-samples (get enums enum))]])]]]]]))

(defn omit-label?
  [label ref]
  (s/includes? (s/lower-case (name ref))
               (s/lower-case (name label))))


(defn- edge-label?
  [edge-labels? label ref]
  (case edge-labels?
    :minimal (omit-label? label ref) #_(not (or (= label ref)
                      (= (name label) (inflect/plural ref))))
    true true
    false))

;;; Graphviz size is inches, width first, and only shrinks (keeping aspect ratio).
;;; Browsers show dot's SVG at 96px/in.
(defn- graph-size
  "Graphviz size attr for a maximum `width`/`height` in pixels; either may be nil."
  [width height]
  (let [in #(if % (/ % 96.0) 10000)]
    (str (in width) "," (in height))))

;;; dot seeds within-rank order from input order, so this tends to put same-category kinds near each other
(defn- category-sorted
  "`kinds` entries sorted by their category's position in `categories`, then by name."
  [kinds categories]
  (let [pos (zipmap (keys categories) (range))]
    (sort-by (fn [[kind {:keys [category] :or {category :default}}]]
               [(get pos category Integer/MAX_VALUE) (name kind)])
             kinds)))

(defn- wrap-label
  "`s` split over two lines at the camelCase or -_ boundary that best balances them, if longer than `n`."
  [s n]
  (let [breaks (when (and n (> (count s) n))
                 (for [i (range 1 (count s))
                       :let [a (.charAt s (dec i)) b (.charAt s i)]
                       :when (or (#{\- \_ \space} a)
                                 (and (Character/isLowerCase a) (Character/isUpperCase b)))]
                   i))]
    (if (seq breaks)
      (let [i (apply min-key #(max % (- (count s) %)) breaks)]
        (str (s/trimr (subs s 0 i)) "\n" (subs s i)))
      s)))

(defn- graph-spec
  "Build a hyperphor.multitool.graph spec (default attrs plus node and edge lists) for `schema`.
  Nodes and edges carry the DOM ids and classes of hyperphor.alzabo.render."
  [schema]
  (let [{:keys [kinds categories render]} (with-graph-defaults schema)
        {:keys [orientation width height edge-labels? xlabels? taxonomy? graph-attrs node-attrs edge-attrs label-wrap]} render
        clean (fn [kind] (s/replace (name kind) \- \_))]
    {:name "schema"
     :graph-attrs (merge {:rankdir (case orientation
                                     :horizontal "LR"
                                     :vertical "TB")}
                         (when (or width height)
                           {:size (graph-size width height)})
                         graph-attrs)
     :node-attrs node-attrs
     :edge-attrs edge-attrs
     :nodes (for [[kind {:keys [doc category icon] :as kind-def :or {category :default}}] (category-sorted kinds categories)]
              [(clean kind)
               (merge {:URL (kind-url kind)
                       :id (render/node-id kind)
                       :class (str "kind " (render/category-class category))
                       :label (str (when icon (str icon " ")) (wrap-label (name kind) label-wrap))
                       :tooltip (or doc (name kind))
                       :fillcolor (get-in categories [category :color])}
                      (get-in categories [category :node-attrs])
                      (:node-attrs kind-def))])
     :edges (for [{:keys [id class from to field cardinality]} (render/graph-edges schema)]
              (if (= class "rel")
                [(clean from)
                 (clean to)
                 (merge {:id id :class class
                         :arrowhead (if (= cardinality :many) "crow" "normal")}
                        (when taxonomy? {:constraint false})
                        (when (edge-label? edge-labels? field to)
                          ;; Leading space keeps the label off its edge; dot has no edge label margin
                          {(if xlabels? :xlabel :label) (str " " (name field))}))]
                ;; Inheritance edges, dashed (child -> parent); with :taxonomy? laid out parent-first so the tree reads top-down
                (if taxonomy?
                  [(clean to)
                   (clean from)
                   {:id id :class class
                    :style "dashed" :dir "back" :arrowtail "empty" :color "#4CAF50" :penwidth "2.0"}]
                  [(clean from)
                   (clean to)
                   {:id id :class class
                    :style "dashed" :arrowhead "empty" :color "#4CAF50" :penwidth "2.0"}])))}))

(defn- dot-attrs
  [m]
  (s/join "," (for [[k v] m :when (some? v)]
                (format "%s=%s" (name k) (pr-str (if (keyword? v) (name v) (str v)))))))

;;; Translucent tint of a #rrggbb category color for the cluster background; other color forms get no fill
(defn- cluster-fill
  [color]
  (when (and (string? color) (re-matches #"#[0-9a-fA-F]{6}" color))
    (str color "40")))

(defn- cluster-specs
  "[[cluster-id attrs node-ids]...], one per category in use, if :clusters? and 2+ categories are used.
  Uncategorized kinds stay outside any cluster."
  [schema]
  (let [{:keys [kinds categories render]} (with-graph-defaults schema)
        groups (group-by (fn [[_ kdef]] (:category kdef)) kinds)
        used (filter #(and (not= % :default) (get groups %)) (keys categories))]
    (when (and (:clusters? render) (> (count used) 1))
      (for [cat used
            :let [{:keys [color label cluster-attrs]} (get categories cat)]]
        [(str "cluster_" (name cat))
         (merge {:label (or label (inflect/titleize (name cat)))
                 :style "rounded,filled"
                 :color color
                 :fillcolor (or (cluster-fill color) "white")
                 :penwidth 1.5
                 :fontname "Helvetica-Bold"
                 :fontsize 13
                 :labeljust "l"}
                cluster-attrs)
         (map (fn [[kind _]] (s/replace (name kind) \- \_)) (get groups cat))]))))

;;; multitool's spec->dot has no subgraphs; a node mentioned in a cluster joins it even if declared earlier
(defn- add-clusters
  "Splice `clusters` (as from cluster-specs) into `dot` source as subgraph statements."
  [dot clusters]
  (if (empty? clusters)
    dot
    (let [close (s/last-index-of dot "}")]
      (str (subs dot 0 close)
           (s/join (for [[id attrs nodes] clusters]
                     (format "subgraph %s {\ngraph [%s];\n%s\n}\n"
                             (pr-str id) (dot-attrs attrs)
                             (s/join " " (map #(str (pr-str %) ";") nodes)))))
           (subs dot close)))))

;;; schema.dot is written before unflattening, which reformats the source
(defn- unflatten
  "`dot` passed through Graphviz unflatten -f -l `levels`; unchanged if `levels` is nil or unflatten fails."
  [dot levels]
  (if levels
    (let [{:keys [exit out]} (try (shell/sh "unflatten" "-f" "-l" (str levels) :in dot)
                                  (catch java.io.IOException _ nil))]
      (if (= exit 0) out dot))
    dot))

;;; Requires installation of graphviz ('brew install graphviz' on Mac)
(defn- graphviz
  "Output of Graphviz `cmd` run with `args` on `dot`."
  [cmd dot & args]
  (let [{:keys [exit out err]} (apply shell/sh cmd (concat args [:in dot]))]
    (if (zero? exit) out (throw (ex-info (str cmd " failed: " err) {:args args})))))

(defn- packed-svg
  "SVG of `spec` with isa edges laid out alone, components packed, and rel edges then drawn as straight lines."
  [spec levels]
  (let [rel? #(= "rel" (:class (nth % 2)))
        laid (graphviz "dot" (unflatten (graph/spec->dot (update spec :edges #(remove rel? %))) levels)
                       "-Gpack=true" "-Gpackmode=node" "-Tdot")
        rels (filter #(s/includes? % " -> ")
                     (s/split-lines (graph/spec->dot {:edges (filter rel? (:edges spec))})))
        close (s/last-index-of laid "}")]
    (graphviz "neato" (str (subs laid 0 close) (s/join "\n" rels) "\n}\n") "-n2" "-Gsplines=false" "-Tsvg")))

(defn- write-graphviz
  "Write `dot-file` and <dot-file>.svg for `schema`; returns the SVG."
  [schema dot-file]
  (let [{levels :unflatten pack? :pack?} (:render (with-graph-defaults schema))
        spec (graph-spec schema)
        dot (add-clusters (graph/spec->dot spec) (cluster-specs schema))
        svg (if pack?
              (packed-svg spec levels)
              (graph/dot->format (unflatten dot levels) "svg"))]
    (println "Writing " dot-file)
    (spit dot-file dot)
    (spit (str dot-file ".svg") svg)
    svg))

(defn- inline-svg
  "`svg` (Graphviz output) made suitable for inlining: no prolog or comments, and sized by CSS via its viewBox."
  [svg]
  (-> svg
      (s/replace #"(?s)<\?xml.*?\?>" "")
      (s/replace #"(?s)<!DOCTYPE.*?>" "")
      (s/replace #"(?s)<!--.*?-->" "")
      (s/replace-first #"<svg width=\"[^\"]*\" height=\"[^\"]*\"" "<svg id=\"az-graph\"")
      s/trim))

(defn- copy-resource
  [resource output-path file]
  (if-let [r (io/resource resource)]
    (io/copy (io/reader r) (io/file (output-file output-path file)))
    (throw (ex-info (str "Missing resource " resource "; build it with `lein cljsbuild once uberjar`") {}))))

(defn schema->html
  "Generate HTML docs for a schema, including .svg and related files, writing them to output-path."
  [{:keys [kinds enums title] :as schema} output-path]
  (let [ctx (static-ctx schema)]
    (fs/mkdirs output-path)
    ;; Write out the schema itself – used by autocomplete, enflame, etc
    (with-open [o (clojure.java.io/writer (output-file output-path "schema.edn"))]
      (pp/pprint schema o))
    (spit (output-file output-path "schema.js") (schema-js schema))
    (doseq [kind (keys kinds)]
      (html-out output-path
                (str (name kind) ".html")
                (format "%s - %s - Alzabo" (name kind) title)
                schema
                (render/kind-page ctx kind)))
    (doseq [enum (keys enums)]
      (html-out output-path
                (str (name enum) ".html")
                (format "%s - %s - Alzabo" (name enum) title)
                schema
                (render/enum-page ctx enum)))
    (let [svg (write-graphviz schema (output-file output-path "schema.dot"))]
      (html-out output-path
                "index.html"
                (format "%s - Alzabo" title)
                schema
                (index->html schema (inline-svg svg))))
    (copy-resource "public/alzabo.css" output-path "alzabo.css")
    ;; The uberjar build is a single file
    (copy-resource "public/jsu/client.js" output-path "client.js")
    nil))
